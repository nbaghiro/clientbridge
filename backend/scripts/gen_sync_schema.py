"""Generate the PowerSync AppSchema from the models and the tables in the sync streams."""

from __future__ import annotations

import re
from pathlib import Path
from typing import NamedTuple, TypedDict

from sqlalchemy import BigInteger, Boolean, Float, Integer, Numeric, SmallInteger
from sqlalchemy.types import TypeEngine

from clientbridge.models import Base

ROOT = Path(__file__).resolve().parents[2]  # backend/scripts/<file> → repo root
SYNC_STREAMS = ROOT / "infra" / "powersync" / "sync-rules.yaml"
OUT = ROOT / "frontend" / "packages" / "sync" / "src" / "schema.ts"

HEADER = """\
// AUTO-GENERATED by `make gen-sync-schema` from the backend SQLAlchemy models + sync streams.
// Do NOT edit by hand — change the models (and infra/powersync/sync-rules.yaml), then regenerate.
// `id` is the implicit text PK; money = integer cents; json/arrays/timestamps stored as text.
import { column, Schema, Table } from "@powersync/common";
"""


# Device-only tables: kept in local SQLite, never uploaded or synced (recent searches, read marks).
LOCAL_ONLY = {
    "device_prefs": {"value": "text", "updated_at": "text"},
    "business_selection": {"business_id": "text"},
    "hours_outbox": {
        "business_id": "text",
        "staff_id": "text",
        "actor_id": "text",
        "payload": "text",
        # the week the proposal was edited from, so a conflict can rebase only the changed days
        "base": "text",
        "state": "text",
        "predecessor_id": "text",
        "result_revision": "integer",
        "attempt_count": "integer",
        "retry_at": "integer",
        "error_code": "text",
        "created_at": "text",
        "sequence": "integer",
    },
}


def gen_local_table(name: str, columns: dict[str, str]) -> str:
    cols = [f"        {col}: column.{kind}," for col, kind in columns.items()]
    return "\n".join(
        [f"const {name} = new Table(", "    {", *cols, "    },", "    { localOnly: true },", ");"]
    )


def stream_columns(rules: str | None = None) -> dict[str, dict[str, list[str]]]:
    """Each stream's explicit data projections; reject syntax that could broaden the replica."""
    streams: dict[str, dict[str, list[str]]] = {}
    stream = ""
    in_queries = False
    for line in (SYNC_STREAMS.read_text() if rules is None else rules).splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        if indent <= 4:
            if indent == 2 and stripped.endswith(":"):
                stream = stripped[:-1]
            in_queries = stripped == "queries:"
            continue
        if not in_queries:
            continue
        match = re.fullmatch(r"- SELECT (.+?) FROM (\w+)(?:\s+WHERE .+)?", stripped)
        if match is None:
            raise ValueError(f"Unsupported sync data projection: {stripped}")
        columns, table = match.groups()
        names = [column.strip() for column in columns.split(",")]
        if not names or any(re.fullmatch(r"[a-z_][a-z_0-9]*", n) is None for n in names):
            raise ValueError(f"Explicit column names required for {table}")
        if "id" not in names:
            raise ValueError(f"Missing replica id for {table}")
        for name in names:
            if name not in Base.metadata.tables[table].c:
                raise ValueError(f"Unknown replica column: {table}.{name}")
            columns_of = streams.setdefault(stream, {}).setdefault(table, [])
            if name not in columns_of:
                columns_of.append(name)
    if not streams:
        raise ValueError("No sync data projections found")
    return streams


def synced_columns(rules: str | None = None) -> dict[str, list[str]]:
    """Union of every stream's projection, per table."""
    projections: dict[str, list[str]] = {}
    for tables in stream_columns(rules).values():
        for table, names in tables.items():
            for name in names:
                if name not in projections.setdefault(table, []):
                    projections[table].append(name)
    return projections


def synced_tables() -> list[str]:
    return list(published_columns())


class Statements(NamedTuple):
    ctes: dict[str, str]
    queries: list[str]


def stream_statements(rules: str | None = None) -> dict[str, Statements]:
    """Each stream's CTEs and queries as written."""
    streams: dict[str, Statements] = {}
    section = ""
    current = Statements({}, [])
    for line in (SYNC_STREAMS.read_text() if rules is None else rules).splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        if indent <= 4:
            if indent == 2 and stripped.endswith(":"):
                current = streams.setdefault(stripped[:-1], Statements({}, []))
            section = stripped
            continue
        if section == "with:":
            name, _, sql = stripped.partition(": ")
            current.ctes[name] = sql
        elif section == "queries:":
            current.queries.append(stripped.removeprefix("- "))
    return streams


StreamFilters = TypedDict("StreamFilters", {"with": dict[str, str], "where": dict[str, list[str]]})


def stream_filters(rules: str | None = None) -> dict[str, StreamFilters]:
    """Each stream's CTEs and each table's WHERE clauses, for review beside the projections."""
    filters: dict[str, StreamFilters] = {}
    for name, stream in stream_statements(rules).items():
        where: dict[str, list[str]] = {}
        for sql in stream.queries:
            match = _SELECT.fullmatch(sql)
            if match is None:
                raise ValueError(f"Unsupported sync statement: {sql}")
            where.setdefault(match.group(2), []).append(match.group(3) or "")
        filters[name] = {"with": dict(stream.ctes), "where": where}
    return filters


_PARAMETER = re.compile(r"\b(?:auth\.user_id|subscription\.parameter)\([^()]*\)")
_SUBQUERY = re.compile(r"\((SELECT [^()]*)\)")
_SELECT = re.compile(r"SELECT (.+?) FROM (\w+)(?: WHERE (.+))?")
_NAME = re.compile(r"(?<![\w.:'])([a-z_][a-z0-9_]*)\b(?!\s*[.(])")
_KEYWORDS = {"and", "or", "in", "is", "not", "null", "true", "false"}


def _read(select: str, ctes: set[str], found: dict[str, set[str]], *, projected: bool) -> None:
    match = _SELECT.fullmatch(select.strip())
    if match is None or "SELECT" in (match.group(3) or ""):
        raise ValueError(f"Unsupported sync statement: {select}")
    columns, table, where = match.groups()
    names = {n.strip() for n in columns.split(",")} if projected else set()
    names |= {n for n in _NAME.findall(where or "") if n not in _KEYWORDS | ctes}
    for name in names:
        if name not in Base.metadata.tables[table].c:
            raise ValueError(f"Unknown filter column: {table}.{name}")
    found.setdefault(table, set()).update(names)


def _references(sql: str, ctes: set[str], found: dict[str, set[str]], *, projected: bool) -> None:
    sql = re.sub(r"'[^']*'", "''", _PARAMETER.sub(":parameter", sql))
    while (inner := _SUBQUERY.search(sql)) is not None:
        _read(inner.group(1), ctes, found, projected=True)
        sql = f"{sql[: inner.start()]}:subquery{sql[inner.end() :]}"
    _read(sql, ctes, found, projected=projected)


def filter_columns(rules: str | None = None) -> dict[str, set[str]]:
    """The columns PowerSync reads to decide which rows reach whom: CTEs, filters, subqueries."""
    found: dict[str, set[str]] = {}
    for stream in stream_statements(rules).values():
        names = set(stream.ctes)
        for sql in stream.ctes.values():
            _references(sql, names, found, projected=True)
        for sql in stream.queries:
            _references(sql, names, found, projected=False)
    return found


def published_columns(rules: str | None = None) -> dict[str, list[str]]:
    """What replication carries: the device projections, the filter columns and the primary key."""
    projections = synced_columns(rules)
    filters = filter_columns(rules)
    published: dict[str, list[str]] = {}
    for name in [*projections, *(t for t in filters if t not in projections)]:
        table = Base.metadata.tables[name]
        wanted = set(projections.get(name, [])) | filters.get(name, set())
        wanted |= {c.name for c in table.primary_key.columns}
        published[name] = [c.name for c in table.columns if c.name in wanted]
    return published


def ps_type(type_: TypeEngine[object]) -> str:
    """Map a SQLAlchemy column type to one of PowerSync's three client types."""
    if isinstance(type_, Boolean):
        return "integer"
    if isinstance(type_, BigInteger | SmallInteger | Integer):
        return "integer"
    if isinstance(type_, Numeric | Float):
        return "real"
    return "text"  # String/Text/Enum/DateTime/Date/Time/JSONB/ARRAY → text


# Foreign keys that device reads join on and no model index leads with.
REPLICA_INDEXES = {
    "entries": {"entries_source_id": ["source_id"]},
    "payments": {"payments_client": ["client_id"]},
}


def replica_indexes(name: str, projected: list[str]) -> dict[str, list[str]]:
    """Model indexes without a leading business_id (device reads are already one business)."""
    indexes: dict[str, list[str]] = {}
    for idx in sorted(Base.metadata.tables[name].indexes, key=lambda i: i.name or ""):
        columns = [c.name for c in idx.columns]
        if not idx.name or not all(c in projected for c in columns):
            continue
        if columns[0] == "business_id" and len(columns) > 1:
            columns = columns[1:]
        if columns not in indexes.values():
            indexes[re.sub(r"^ix_", "", idx.name)] = columns
    for key, columns in REPLICA_INDEXES.get(name, {}).items():
        if columns not in indexes.values():
            indexes[key] = columns
    return indexes


def gen_table(name: str, projected: list[str]) -> str:
    table = Base.metadata.tables[name]
    cols = [
        f"        {col.name}: column.{ps_type(col.type)},"
        for col in table.columns
        if col.name != "id" and col.name in projected
    ]
    indexes = [
        f"            {key}: [{', '.join(repr(c) for c in columns)}],"
        for key, columns in replica_indexes(name, projected).items()
    ]

    out = [f"const {name} = new Table(", "    {", *cols, "    },"]
    if indexes:
        out += ["    {", "        indexes: {", *indexes, "        },", "    },"]
    out.append(");")
    return "\n".join(out)


def main() -> None:
    projections = synced_columns()
    names = list(projections)
    body = "\n\n".join(
        [
            *(gen_table(n, projections[n]) for n in names),
            *(gen_local_table(n, c) for n, c in LOCAL_ONLY.items()),
        ]
    )
    members = ",\n".join(f"    {n}" for n in [*names, *LOCAL_ONLY])
    content = (
        f"{HEADER}\n"
        f"{body}\n\n"
        f"export const AppSchema = new Schema({{\n{members},\n}});\n\n"
        f'export type Database = (typeof AppSchema)["types"];\n'
    )
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(names)} synced tables)")


if __name__ == "__main__":
    main()
